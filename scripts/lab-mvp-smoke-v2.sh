#!/usr/bin/env bash
# Protocol v2 lab smoke: Anvil (or existing RPC) -> V2 deploy -> write api/.env.lab.v2
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONTRACTS="$ROOT/contracts"
RPC_URL="${RPC_URL:-http://127.0.0.1:8545}"
ANVIL_PID=""
STARTED_ANVIL=0
DEPLOYER_KEY="${DEPLOYER_PRIVATE_KEY:-0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80}"
# Anvil account #1 — lab emergency authority from DeployLabEnvironmentV2
EMERGENCY_KEY="${BLOCKCHAIN_EMERGENCY_PRIVATE_KEY:-0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d}"
DUMMY_ADDR="0x0000000000000000000000000000000000000001"

cleanup() {
  if [[ "$STARTED_ANVIL" -eq 1 && -n "$ANVIL_PID" ]]; then
    kill "$ANVIL_PID" 2>/dev/null || true
  fi
}
trap cleanup EXIT

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "Missing required command: $1" >&2
    exit 1
  }
}

need_cmd forge
need_cmd cast
need_cmd curl

if ! curl -sf -X POST "$RPC_URL" \
  -H 'content-type: application/json' \
  --data '{"jsonrpc":"2.0","method":"eth_chainId","params":[],"id":1}' >/dev/null; then
  need_cmd anvil
  echo "Starting Anvil on $RPC_URL ..."
  anvil --host 127.0.0.1 --port 8545 --chain-id 31337 >/tmp/centralbank-anvil-v2.log 2>&1 &
  ANVIL_PID=$!
  STARTED_ANVIL=1
  for _ in $(seq 1 30); do
    if curl -sf -X POST "$RPC_URL" \
      -H 'content-type: application/json' \
      --data '{"jsonrpc":"2.0","method":"eth_chainId","params":[],"id":1}' >/dev/null; then
      break
    fi
    sleep 0.5
  done
fi

echo "Deploying Protocol v2 lab stack..."
DEPLOY_LOG="$(mktemp)"
(
  cd "$CONTRACTS"
  forge script script/DeployCentralBankV2.s.sol:DeployLabEnvironmentV2 \
    --rpc-url "$RPC_URL" \
    --broadcast \
    --private-key "$DEPLOYER_KEY" \
    -vv
) | tee "$DEPLOY_LOG"

extract() {
  local name="$1"
  grep -E "export ${name}=" "$DEPLOY_LOG" | tail -n1 | sed -E "s/.*export ${name}=[[:space:]]*//" | tr -d '\r'
}

TOKEN_LEDGER="$(extract TOKEN_LEDGER_V2_ADDRESS)"
MINT_BURN="$(extract MINT_BURN_CONTROLLER_V2_ADDRESS)"
ESCROW="$(extract ESCROW_CONTROLLER_V2_ADDRESS)"
EMERGENCY="$(extract EMERGENCY_POLICY_V2_ADDRESS)"
SANCTIONS="$(extract SANCTIONS_POLICY_V2_ADDRESS)"
HOLDING="$(extract HOLDING_LIMIT_POLICY_V2_ADDRESS)"
WATERFALL="$(extract WATERFALL_CONTROLLER_V2_ADDRESS)"

if [[ -z "$TOKEN_LEDGER" || -z "$MINT_BURN" || -z "$ESCROW" || -z "$EMERGENCY" || -z "$SANCTIONS" || -z "$HOLDING" || -z "$WATERFALL" ]]; then
  echo "Failed to parse deployed V2 addresses from forge output" >&2
  exit 1
fi

ENV_FILE="$ROOT/api/.env.lab.v2"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/lab-mvp-smoke-v2.sh — Protocol v2 API cutover wiring
NODE_ENV=development
PORT=3000
LOG_LEVEL=info
PROTOCOL_STACK=v2
BLOCKCHAIN_RPC_URL=$RPC_URL
BLOCKCHAIN_CHAIN_ID=31337
BLOCKCHAIN_OPERATOR_PRIVATE_KEY=$DEPLOYER_KEY
BLOCKCHAIN_EMERGENCY_PRIVATE_KEY=$EMERGENCY_KEY
SIGNER_BACKEND=env
CONTRACT_PERMISSIONING=$DUMMY_ADDR
CONTRACT_WALLET_REGISTRY=$DUMMY_ADDR
CONTRACT_DIGITAL_TOKEN=$DUMMY_ADDR
CONTRACT_CONDITIONAL_PAYMENTS=$DUMMY_ADDR
CONTRACT_TOKEN_LEDGER_V2=$TOKEN_LEDGER
CONTRACT_MINT_BURN_CONTROLLER_V2=$MINT_BURN
CONTRACT_ESCROW_CONTROLLER_V2=$ESCROW
CONTRACT_WATERFALL_CONTROLLER_V2=$WATERFALL
CONTRACT_SANCTIONS_POLICY_V2=$SANCTIONS
CONTRACT_EMERGENCY_POLICY_V2=$EMERGENCY
CONTRACT_HOLDING_LIMIT_POLICY_V2=$HOLDING
JWT_SECRET=development-secret-key-min-32-chars!
JWT_ISSUER=centralbank-lab
JWT_AUDIENCE=centralbank-api
JWT_EXPIRES_IN=1h
PARAMETERS_FILE=$ROOT/envs/lab/ecb-core/parameters.json
PROFILE_FILE=$ROOT/profiles/eurosystem-reference.json
ENABLE_API_DOCS=true
ALLOW_DEMO_IDENTITIES=false
CORS_ORIGIN=http://localhost:3001
EOF

echo ""
echo "Wrote $ENV_FILE"
echo "Next:"
echo "  cd api && cp .env.lab.v2 .env && npm ci && npm run dev"
echo "  curl -s http://localhost:3000/api/v1/health/live"
echo ""
echo "PROTOCOL_STACK=v2 routes mint/burn/freeze/escrow/waterfall/pause through V2 controllers."
echo "ConditionalPayments and WalletRegistry remain v1-only and are rejected on this stack."
