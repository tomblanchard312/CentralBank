#!/usr/bin/env bash
# Reference MVP lab smoke: Anvil (or existing RPC) -> v1 deploy -> write api/.env.lab
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONTRACTS="$ROOT/contracts"
RPC_URL="${RPC_URL:-http://127.0.0.1:8545}"
ANVIL_PID=""
STARTED_ANVIL=0

cleanup() {
  # KEEP_ANVIL=1 leaves the chain up for demo-checklist / API follow-on steps.
  if [[ "$STARTED_ANVIL" -eq 1 && "${KEEP_ANVIL:-0}" != "1" && -n "$ANVIL_PID" ]]; then
    kill "$ANVIL_PID" 2>/dev/null || true
  fi
}
trap cleanup EXIT

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "Missing required command: $1" >&2
    exit 1
  }
}

need_cmd forge
need_cmd cast
need_cmd curl

if ! curl -sf -X POST "$RPC_URL" \
  -H 'content-type: application/json' \
  --data '{"jsonrpc":"2.0","method":"eth_chainId","params":[],"id":1}' >/dev/null; then
  need_cmd anvil
  echo "Starting Anvil on $RPC_URL ..."
  nohup anvil --host 0.0.0.0 --port 8545 --chain-id 31337 >/tmp/centralbank-anvil.log 2>&1 &
  ANVIL_PID=$!
  STARTED_ANVIL=1
  for _ in $(seq 1 30); do
    if curl -sf -X POST "$RPC_URL" \
      -H 'content-type: application/json' \
      --data '{"jsonrpc":"2.0","method":"eth_chainId","params":[],"id":1}' >/dev/null; then
      break
    fi
    sleep 0.5
  done
  if [[ "${KEEP_ANVIL:-0}" == "1" ]]; then
    disown "$ANVIL_PID" 2>/dev/null || true
  fi
fi

echo "Deploying v1 lab stack..."
DEPLOY_LOG="$(mktemp)"
(
  cd "$CONTRACTS"
  forge script script/DeployCentralBank.s.sol:DeployLabEnvironment \
    --rpc-url "$RPC_URL" \
    --broadcast \
    --start-fresh \
    --private-key "${DEPLOYER_PRIVATE_KEY:-0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80}" \
    -vv
) | tee "$DEPLOY_LOG"

extract() {
  local name="$1"
  grep -E "export ${name}=" "$DEPLOY_LOG" | tail -n1 | sed -E "s/.*export ${name}=[[:space:]]*//" | tr -d '\r'
}

PERMISSIONING="$(extract PERMISSIONING_ADDRESS)"
WALLET_REGISTRY="$(extract WALLET_REGISTRY_ADDRESS)"
DIGITAL_TOKEN="$(extract DIGITAL_TOKEN_ADDRESS)"
CONDITIONAL_PAYMENTS="$(extract CONDITIONAL_PAYMENTS_ADDRESS)"

if [[ -z "$PERMISSIONING" || -z "$WALLET_REGISTRY" || -z "$DIGITAL_TOKEN" || -z "$CONDITIONAL_PAYMENTS" ]]; then
  echo "Failed to parse deployed addresses from forge output" >&2
  exit 1
fi

ENV_FILE="$ROOT/api/.env.lab"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/lab-mvp-smoke.sh — reference MVP lab wiring (v1 path)
NODE_ENV=development
PORT=3000
LOG_LEVEL=info
BLOCKCHAIN_RPC_URL=$RPC_URL
BLOCKCHAIN_CHAIN_ID=31337
BLOCKCHAIN_OPERATOR_PRIVATE_KEY=${DEPLOYER_PRIVATE_KEY:-0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80}
SIGNER_BACKEND=env
CONTRACT_PERMISSIONING=$PERMISSIONING
CONTRACT_WALLET_REGISTRY=$WALLET_REGISTRY
CONTRACT_DIGITAL_TOKEN=$DIGITAL_TOKEN
CONTRACT_CONDITIONAL_PAYMENTS=$CONDITIONAL_PAYMENTS
JWT_SECRET=development-secret-key-min-32-chars!
JWT_ISSUER=centralbank-lab
JWT_AUDIENCE=centralbank-api
JWT_EXPIRES_IN=1h
PARAMETERS_FILE=$ROOT/envs/lab/ecb-core/parameters.json
PROFILE_FILE=$ROOT/profiles/eurosystem-reference.json
ENABLE_API_DOCS=true
ALLOW_DEMO_IDENTITIES=true
CORS_ORIGIN=http://localhost:3001
EOF

echo ""
echo "Wrote $ENV_FILE"
echo "Next:"
echo "  cd api && cp .env.lab .env && npm ci && npm run dev"
echo "  curl -s http://localhost:3000/api/v1/health/live"
echo "  ./scripts/lab-mvp-demo-checklist.sh"
echo ""
echo "Reference MVP path is v1. Protocol v2 remains: cd contracts && make deploy-local-v2"
